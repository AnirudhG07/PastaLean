#!/usr/bin/env python3
"""PastaBench — build and maintain the shipped Python→Lean verification benchmark.

The benchmark is a curated slice of the `cp_harness` LeetCode corpus, laid out so that
**machine-generated Lean and hand-written proofs never share a file**:

    PastaBench/leetcode/<Module>/          (and PastaBench/stdlib/<Module>/)
        problem.txt             the problem statement
        meta.json               task_id, method, params, difficulty, bucket, features, module
        solution.py             the program as it came from the dataset — untouched
        solution_contracts.py   the same program annotated with contracts; translated in preference
        tests.json              the test cases (input/output), for the runnable twin
        Generated.lean          AUTOGENERATED — `regen` overwrites it, never edit
        Proofs.lean             HUMAN-WRITTEN — imports Generated, `regen` never touches it

`Generated.lean` is wrapped in `namespace PastaBench.leetcode.<Module>` so 300 problems can
coexist in one library; `Proofs.lean` opens it and states the theorems.

Subcommands
    select      choose the problems from a dataset and write manifest.json
    materialize create the per-problem directories from the manifest (seeds Proofs.lean stubs)
    contracts   write + verify solution_contracts.py per unit — generate → verify → repair,
                gated deterministically (docs/contract-qa.md). Resumable; nothing that fails a
                gate is ever written.
    regen       re-translate the Python → Generated.lean (Proofs.lean untouched)
    status      report proof coverage: how many units have contracts / sorry-free proofs

    python3 PastaBench/pastabench.py select --dataset cp_harness/dataset_leetcode
    python3 PastaBench/pastabench.py materialize
    python3 PastaBench/pastabench.py contracts --track humaneval --attempts 0   # verify, no LLM
    python3 PastaBench/pastabench.py contracts --track humaneval --attempts 2   # + repair
    python3 PastaBench/pastabench.py regen --only HouseRobberIii
    python3 PastaBench/pastabench.py status
"""
from __future__ import annotations

import argparse
import ast
import concurrent.futures
import json
import math
import random
import re
import shutil
import subprocess
import sys
from pathlib import Path

BENCH_ROOT = Path(__file__).resolve().parent
REPO_ROOT = BENCH_ROOT.parent
MANIFEST = BENCH_ROOT / "manifest.json"
LEETCODE_DIR = BENCH_ROOT / "leetcode"
#: The second track: real Python standard-library algorithms, hand-curated rather than sampled.
#: Same two-file rule, `PastaBench.stdlib.<Module>` namespace.
STDLIB_DIR = BENCH_ROOT / "stdlib"
#: The third track: HumanEval+ (evalplus/humanevalplus), ingested into the same per-problem format.
HUMANEVAL_DIR = BENCH_ROOT / "humaneval"
#: The Lean root module, listing every problem's `Proofs` — regenerated by `materialize`.
ROOT_MODULE = REPO_ROOT / "PastaBench.lean"
LEAN_NAMESPACE = "PastaBench.leetcode"
STDLIB_NAMESPACE = "PastaBench.stdlib"
HUMANEVAL_NAMESPACE = "PastaBench.humaneval"

#: Selection sizes. `term` = Tier-0 (bare Lean term, provable today); `loop` = `Id.run do`
#: (for/while/mutation — reachable via the mvcgen and `pyWhile` tracks).
TERM_QUOTA = {"Easy": 40, "Medium": 47, "Hard": 13}
LOOP_QUOTA = {"class": 25, "while": 100, "for": 75}
#: Within a `loop` feature bucket, how to spread difficulty.
LOOP_DIFF_MIX = {"Easy": 0.25, "Medium": 0.50, "Hard": 0.25}

#: A contract marker call, used both to validate an LLM rewrite and to report coverage.
CONTRACT_RE = re.compile(r"\b(Requires|Ensures|Invariant|Decreases|Assert|Assume)\s*\(")


# -- naming --------------------------------------------------------------------------------

def module_name(problem: str) -> str:
    """`house-robber-iii` → `HouseRobberIii`; a leading digit gets an `N` (Lean identifiers
    cannot start with one), so `4sum` → `N4sum`."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", problem) if p]
    name = "".join(p[:1].upper() + p[1:] for p in parts)
    return ("N" + name) if name[:1].isdigit() else name


# -- shape classification ------------------------------------------------------------------

def classify(lean_src: str, py_src: str) -> dict:
    """The features that decide which bucket a problem lands in. `term` is the load-bearing one:
    a solution with no `Id.run` compiled to a bare Lean term and is provable with the existing
    assert/contract machinery; everything else needs the loop tracks."""
    return {
        "term": "Id.run" not in lean_src,
        "while": bool(re.search(r"^\s*while ", lean_src, re.M)),
        "for": bool(re.search(r"^\s*for ", lean_src, re.M)),
        "class": bool(re.search(r"^\s*class ", py_src, re.M)),
        "recursive": bool(re.search(r"\bpartial def\b", lean_src)),
    }


def survey(dataset: Path) -> list[dict]:
    """Every problem in `dataset` that converted AND compiled, with its shape features."""
    rows = []
    for prob in sorted(p for p in dataset.iterdir() if p.is_dir()):
        lean, status = prob / "lean/sol_0.lean", prob / "lean/sol_0.status"
        meta, py, tests = prob / "meta.json", prob / "solutions/sol_0.py", prob / "tests/tests.json"
        if not all(f.exists() for f in (lean, status, meta, py, tests)):
            continue
        if status.read_text().strip() != "ok":
            continue
        lean_src, py_src = lean.read_text(), py.read_text()
        try:
            cases = json.loads(tests.read_text())
        except json.JSONDecodeError:
            continue
        if not cases:
            continue
        m = json.loads(meta.read_text())
        rows.append({
            "problem": prob.name,
            "module": module_name(prob.name),
            "difficulty": m.get("difficulty", "Unknown"),
            "method": m.get("method"),
            "params": m.get("params", []),
            "n_tests": len(cases),
            "lean_lines": len(lean_src.splitlines()),
            "py_lines": len(py_src.splitlines()),
            **classify(lean_src, py_src),
        })
    return rows


# -- selection -----------------------------------------------------------------------------

def _rank(row: dict) -> tuple:
    """Bench-worthiness, best first: a problem worth proving is well-tested and small enough that
    a human can actually finish the proof. Ties break on name so selection is reproducible."""
    return (-min(row["n_tests"], 40), row["lean_lines"], row["problem"])


def _take(pool: list[dict], n: int, seed: int) -> list[dict]:
    """The `n` best-ranked of `pool`, with a seeded shuffle first so the pick isn't a pure
    prefix of one ranking (which would bias every bucket toward the same tiny problems)."""
    pool = list(pool)
    random.Random(seed).shuffle(pool)
    return sorted(pool, key=_rank)[:n]


def _feature_of(r: dict) -> str | None:
    """The language feature that makes a `loop` problem hard: a class, a `while`, else a `for`."""
    if r["class"]:
        return "class"
    if r["while"]:
        return "while"
    return "for" if r["for"] else None


def _pick(rows: list[dict], seed: int, scale: float = 1.0) -> list[dict]:
    """The stratified selection, tagged with `bucket`/`feature`. `scale` inflates every quota
    (curation gates a `scale>1` candidate pool, then re-picks the final 300 from the survivors at
    `scale=1`), so `select` and `curate` share exactly one stratification rule."""
    chosen: dict[str, dict] = {}

    # Bucket `term`: Tier-0 problems, spread across difficulty.
    for diff, quota in TERM_QUOTA.items():
        q = math.ceil(quota * scale)
        pool = [r for r in rows if r["term"] and r["difficulty"] == diff]
        for r in _take(pool, q, seed):
            chosen[r["problem"]] = {**r, "bucket": "term", "feature": "term"}

    # Bucket `loop`: `Id.run do` problems, stratified by the feature that makes them hard
    # (a class, a `while`, or a plain `for`) and then by difficulty inside each feature.
    for feature, quota in LOOP_QUOTA.items():
        q = math.ceil(quota * scale)
        pool = [r for r in rows
                if not r["term"] and _feature_of(r) == feature and r["problem"] not in chosen]
        picked: list[dict] = []
        for diff, share in LOOP_DIFF_MIX.items():
            sub = [r for r in pool if r["difficulty"] == diff and r not in picked]
            picked += _take(sub, round(q * share), seed + 1)
        # Backfill from whatever the difficulty mix could not supply, so the quota is met.
        if len(picked) < q:
            rest = [r for r in pool if r not in picked]
            picked += _take(rest, q - len(picked), seed + 2)
        for r in picked[:q]:
            chosen[r["problem"]] = {**r, "bucket": "loop", "feature": feature}

    return sorted(chosen.values(), key=lambda r: (r["bucket"], r["feature"],
                                                  r["difficulty"], r["problem"]))


def select(dataset: Path, seed: int) -> dict:
    rows = survey(dataset)
    entries = _pick(rows, seed)
    manifest = {
        "source_dataset": str(dataset),
        "source_hf_repo": "newfacade/LeetCodeDataset",
        "seed": seed,
        "counts": _counts(entries),
        "problems": entries,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"[*] Selected {len(entries)} problems -> {MANIFEST}")
    _print_counts(manifest["counts"])
    return manifest


def _counts(entries: list[dict]) -> dict:
    out: dict = {"total": len(entries), "by_bucket": {}, "by_difficulty": {}, "by_feature": {}}
    for e in entries:
        for key, val in (("by_bucket", e["bucket"]), ("by_difficulty", e["difficulty"]),
                         ("by_feature", e["feature"])):
            out[key][val] = out[key].get(val, 0) + 1
    return out


def _print_counts(counts: dict) -> None:
    for key in ("by_bucket", "by_feature", "by_difficulty"):
        pairs = ", ".join(f"{k}={v}" for k, v in sorted(counts[key].items()))
        print(f"      {key.replace('by_', ''):>10}: {pairs}")


# -- materialization -----------------------------------------------------------------------

#: Lines a generated file keeps ABOVE the namespace: `import`s must be at module top, and the
#: `open`/`set_option` preamble applies to the whole file anyway.
_HEADER_RE = re.compile(r"^\s*(import|open|set_option)\b")


def namespaced(lean_src: str, module: str, prefix: str = LEAN_NAMESPACE,
               py_source: str | None = None) -> str:
    """Wrap generated Lean in `namespace <prefix>.<module>` so 300 problems (each defining
    `main`, `inf`, a `Solution` method, …) can be imported into one library without clashing.
    Imports/opens/options stay above the namespace. When `py_source` is given, the exact Python
    that PastaLean converted is embedded as a reference comment, so each `Generated.lean` shows
    its own origin: Python source → the Lean below → proofs in `Proofs.lean`."""
    lines = lean_src.splitlines()
    cut = 0
    for i, line in enumerate(lines):
        if line.strip() and not _HEADER_RE.match(line):
            break
        cut = i + 1
    header = [l for l in lines[:cut]]
    body = lines[cut:]
    ns = f"{prefix}.{module}"
    banner = [
        "",
        "/-! AUTOGENERATED by PastaLean — DO NOT EDIT. Regenerate with",
        "    `python3 PastaBench/pastabench.py regen`. Hand-written proofs go in `Proofs.lean`. -/",
        "",
    ]
    if py_source is not None:
        # `-/` inside the source would close the Lean block comment early; neutralise it.
        safe = py_source.replace("-/", "- /").rstrip()
        banner += ["/- Python source converted to produce the Lean below "
                   "(the exact input to PastaLean):", ""] \
            + safe.splitlines() + ["-/", ""]
    # The core transpiler wraps user code in a placeholder `namespace PastaLean.User.Root`. Rename it
    # in place to this module's namespace (flat, no nesting) so 300+ problems don't clash and the
    # `Proofs.lean` references still resolve to `<prefix>.<module>.<name>`.
    if any(l.strip() == "namespace PastaLean.User.Root" for l in body):
        body = [f"namespace {ns}" if l.strip() == "namespace PastaLean.User.Root"
                else f"end {ns}" if l.strip() == "end PastaLean.User.Root"
                else l for l in body]
        return "\n".join(header + banner + body + [""])
    banner += [f"namespace {ns}", ""]
    return "\n".join(header + banner + body + ["", f"end {ns}", ""])


PROOFS_TEMPLATE = '''\
import PastaBench.leetcode.{module}.Generated

/-!
# {problem} — hand-written proofs  ({difficulty}, bucket `{bucket}`)

HUMAN-WRITTEN. `pastabench.py regen` never touches this file; it only rewrites `Generated.lean`.

Worked reference: `PastaBench/leetcode/SmallestEvenMultiple/Proofs.lean`.

Workflow:
1. Add contracts (`Requires` / `Ensures` / `Invariant` / `Assert`) to `solution.py`.
2. `python3 PastaBench/pastabench.py regen --only {module}` — PastaLean states the theorem in
   `Generated.lean` and discharges what it can, leaving `sorry` for the rest.
3. Restate that theorem here and prove it by hand.

Restating keeps the human proof independent of regeneration. To guarantee the restatement did
not drift from what PastaLean generated, follow it with the fidelity check — `rfl` typechecks
only if both statements are definitionally equal:

```
theorem {method}_spec' : <the generated statement> := by
  <hand-written proof>

example : {method}_spec = {method}_spec' := rfl   -- statements agree
```
-/

namespace {namespace}

-- TODO: state and prove the correctness theorem for `{method}`.

end {namespace}
'''


def materialize(force_proofs: bool = False) -> None:
    manifest = json.loads(MANIFEST.read_text())
    dataset = REPO_ROOT / manifest["source_dataset"]
    LEETCODE_DIR.mkdir(parents=True, exist_ok=True)
    made = kept = 0
    for entry in manifest["problems"]:
        src = dataset / entry["problem"]
        dst = LEETCODE_DIR / entry["module"]
        dst.mkdir(parents=True, exist_ok=True)

        shutil.copyfile(src / "solutions/sol_0.py", dst / "solution.py")
        shutil.copyfile(src / "tests/tests.json", dst / "tests.json")
        if (src / "problem.txt").exists():
            shutil.copyfile(src / "problem.txt", dst / "problem.txt")
        (dst / "meta.json").write_text(json.dumps(
            {k: entry[k] for k in ("problem", "module", "method", "params", "difficulty",
                                   "bucket", "feature", "n_tests")}, indent=2) + "\n")
        (dst / "Generated.lean").write_text(
            namespaced((src / "lean/sol_0.lean").read_text(), entry["module"],
                       py_source=(src / "solutions/sol_0.py").read_text()))

        proofs = dst / "Proofs.lean"
        if proofs.exists() and not force_proofs:
            kept += 1
        else:
            proofs.write_text(PROOFS_TEMPLATE.format(
                module=entry["module"], problem=entry["problem"],
                difficulty=entry["difficulty"], bucket=entry["bucket"],
                method=entry["method"] or "solve",
                namespace=f"{LEAN_NAMESPACE}.{entry['module']}"))
            made += 1
    write_root_module(manifest)
    print(f"[*] Materialized {len(manifest['problems'])} problems into {LEETCODE_DIR}")
    print(f"      Proofs.lean: {made} created, {kept} preserved")


def stdlib_modules() -> list[Path]:
    """The hand-curated stdlib-algorithm directories (each holding a `solution.py`)."""
    if not STDLIB_DIR.is_dir():
        return []
    return sorted(d for d in STDLIB_DIR.iterdir() if (d / "solution.py").exists())


def humaneval_modules() -> list[Path]:
    """The ingested HumanEval+ directories (each holding a `solution.py`)."""
    if not HUMANEVAL_DIR.is_dir():
        return []
    return sorted(d for d in HUMANEVAL_DIR.iterdir() if (d / "solution.py").exists())


def write_root_module(manifest: dict) -> None:
    """`PastaBench.lean` — imports every problem's `Proofs`, which in turn imports its
    `Generated`, so `lake build PastaBench` checks the whole benchmark."""
    # NOTE: the HumanEval+ track is deliberately NOT in this root — it is not compile-gated (some
    # problems `compile_fail`), so it is built as individual targets by `run_humaneval_overnight.sh`
    # rather than folded into `lake build PastaBench`, which must stay green for the curated 300.
    imports = "\n".join([f"import {LEAN_NAMESPACE}.{e['module']}.Proofs"
                           for e in manifest["problems"]]
                        + [f"import {STDLIB_NAMESPACE}.{d.name}.Proofs"
                           for d in stdlib_modules()])
    ROOT_MODULE.write_text(
        imports + "\n\n"
        "/-! # PastaBench — Python→Lean verification benchmark\n\n"
        f"{manifest['counts']['total']} LeetCode problems plus {len(stdlib_modules())} stdlib\n"
        "algorithms: Python source, test cases, the Lean PastaLean generates from it, and\n"
        "hand-written correctness proofs.\n"
        "Generated by `PastaBench/pastabench.py materialize`. -/\n")


# -- contracts (LLM pre-pass) ----------------------------------------------------------------

#: Written next to `solution.py`; `source_of` prefers it, so `regen` translates the annotated
#: program and PastaLean has something to state a theorem about.
CONTRACTS_FILE = "solution_contracts.py"


def _entry_defs(source: str) -> set[str]:
    """Top-level function names, so a rewrite that silently dropped one can be rejected."""
    try:
        return {n.name for n in ast.parse(source).body if isinstance(n, ast.FunctionDef)}
    except SyntaxError:
        return set()


#: Where the pipeline parks a generated/repaired file unless `--in-place` is given, so a sweep can
#: never clobber a hand-edited `solution_contracts.py`.
QA_OUT_DIR = BENCH_ROOT / "_contract_qa"

TRACK_DIRS = {"leetcode": LEETCODE_DIR, "stdlib": STDLIB_DIR, "humaneval": HUMANEVAL_DIR}


def contracts(args) -> int:
    """Write and verify `solution_contracts.py` per unit.

    One command, one loop: every candidate — whether freshly generated or already on disk — goes
    through the deterministic gates (static / behaviour identity / contract truth / mutation score),
    and a file that fails one is never written. `--attempts 0` is a pure verification sweep and
    makes no LLM calls at all. See `docs/contract-qa.md`; the implementation is
    `pastalean.transpile.contract_qa`."""
    # Prefer the installed package: repair reaches `pastalean.transpile.llm` through it.
    try:
        from pastalean.transpile.contract_qa.__main__ import main as qa_main  # noqa: PLC0415
    except ImportError:
        sys.path.insert(0, str(REPO_ROOT / "src" / "transpile"))
        from contract_qa.__main__ import main as qa_main  # noqa: PLC0415

    argv = [str(TRACK_DIRS[args.track]),
            "--mutants", str(args.mutants), "--mutation-tests", str(args.mutation_tests),
            "--workers", str(args.workers), "--provider", args.provider,
            "--out-dir", str(QA_OUT_DIR), "--attempts", str(args.attempts)]
    if args.only:
        argv += ["--only", *args.only]
    if args.model:
        argv += ["--model", args.model]
    if args.min_mutation_score is not None:
        argv += ["--min-mutation-score", str(args.min_mutation_score)]
    if args.report:
        argv += ["--report", args.report]
    if args.critic:
        argv.append("--critic")
    if args.in_place:
        argv.append("--in-place")
    if args.verbose:
        argv.append("--verbose")
    return qa_main(argv)


# -- curation: contract-gated selection ----------------------------------------------------

CURATE_DIR = BENCH_ROOT / "_curate"          # staging: generated contracts + the gate cache
GATE_CACHE = CURATE_DIR / "gate.json"


def substantive_ensures_count(source: str) -> int:
    """How many NON-TRIVIAL `Ensures(...)` the contracted source states about its output: each must
    mention `Result()` and not be a bare constant bound. This is the 'we can extract a real property'
    gate — a program with 0 is not benchmark-worthy however well it converts.

    The canonical implementation lives with the rest of the static gates, in
    `pastalean.transpile.contract_qa.static_gates`."""
    try:
        from pastalean.transpile.contract_qa.static_gates import (  # noqa: PLC0415
            substantive_ensures_count as impl)
    except ImportError:
        sys.path.insert(0, str(REPO_ROOT / "src" / "transpile"))
        from contract_qa.static_gates import substantive_ensures_count as impl  # noqa: PLC0415

    return impl(source)


def _load_gate() -> dict:
    if GATE_CACHE.exists():
        return json.loads(GATE_CACHE.read_text())
    return {}


def _save_gate(cache: dict) -> None:
    CURATE_DIR.mkdir(exist_ok=True)
    GATE_CACHE.write_text(json.dumps(cache, indent=2, sort_keys=True) + "\n")


def _gate_contracts(candidates: list[dict], dataset: Path, provider: str, model: str | None,
                    workers: int, min_ensures: int, cache: dict, force: bool) -> None:
    """Stage 1 (LLM, parallel, resumable): run `--contracts` on each candidate's `solution.py`,
    keep it only if the rewrite parses, drops no definition, and states `>= min_ensures` substantive
    `Ensures`. Passing contracts land in `_curate/<Module>.contracts.py`; the verdict caches so an
    interrupted or partial (`--only`) sweep costs nothing to resume."""
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from pastalean.transpile import llm  # noqa: PLC0415

    def work(c: dict) -> tuple[str, dict]:
        mod, prob = c["module"], c["problem"]
        rec = cache.get(mod, {})
        cf = CURATE_DIR / f"{mod}.contracts.py"
        if not force and rec.get("contract") in ("pass", "fail") and (rec["contract"] == "fail" or cf.exists()):
            return mod, rec
        original = (dataset / prob / "solutions/sol_0.py").read_text()
        try:
            annotated = llm.contract_code(original, provider=provider, model=model)
        except Exception as exc:  # noqa: BLE001  (one refusal must not stop the sweep)
            return mod, {**rec, "contract": "fail", "why": f"llm {type(exc).__name__}"}
        if not annotated or not annotated.strip() or not CONTRACT_RE.search(annotated):
            return mod, {**rec, "contract": "fail", "why": "no contracts inserted"}
        if _entry_defs(original) - _entry_defs(annotated):
            return mod, {**rec, "contract": "fail", "why": "dropped definitions"}
        se = substantive_ensures_count(annotated)
        if se < min_ensures:
            return mod, {**rec, "contract": "fail", "why": f"only {se} substantive Ensures", "ensures": se}
        CURATE_DIR.mkdir(exist_ok=True)
        cf.write_text(annotated)
        return mod, {**rec, "contract": "pass", "ensures": se}

    pending = [c for c in candidates
               if force or cache.get(c["module"], {}).get("contract") not in ("pass", "fail")]
    print(f"[contracts] {len(candidates)} candidates, {len(pending)} to annotate "
          f"(provider={provider}, model={model or 'default'}, min_ensures={min_ensures})")
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
        futures = {pool.submit(work, c): c for c in candidates}
        for i, fut in enumerate(concurrent.futures.as_completed(futures), 1):
            mod, rec = fut.result()
            cache[mod] = rec
            if i % 10 == 0 or rec.get("contract") == "pass":
                _save_gate(cache)
            print(f"  [{i}/{len(candidates)}] {rec.get('contract','?'):>4} "
                  f"{('E'+str(rec.get('ensures',''))):>4}  {mod}"
                  + (f"  ({rec.get('why')})" if rec.get("contract") == "fail" else ""))
    _save_gate(cache)


def _gate_compile(candidates: list[dict], cache: dict, force: bool) -> None:
    """Stage 2 (Lean, serial, resumable): translate each contract-passing candidate and compile-check
    the emitted Lean — this is 'PastaLean parses the contracts, states the theorem, and it elaborates
    with its best-effort proof'. One warm backend; verdict cached. `degraded` (pyUnsupported) counts as
    a fail, since a placeholder is not a real theorem."""
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from pastalean import Session  # noqa: PLC0415
    from pastalean.backend import lean as leanmod  # noqa: PLC0415

    todo = [c for c in candidates
            if cache.get(c["module"], {}).get("contract") == "pass"
            and (force or cache[c["module"]].get("compile") not in ("pass", "fail"))]
    print(f"[compile] {len(todo)} contract-passing candidates to compile-check")
    with Session(target="command", mode="both") as session:
        for i, c in enumerate(todo, 1):
            mod = c["module"]
            rec = cache[mod]
            cf = CURATE_DIR / f"{mod}.contracts.py"
            try:
                res = session.translate_file(cf)
            except Exception as exc:  # noqa: BLE001
                rec.update(compile="fail", why=f"translate {type(exc).__name__}")
            else:
                if not res.ok or not (res.lean_code or "").strip():
                    rec.update(compile="fail", why=(res.error or "no output").splitlines()[0][:80])
                elif "pyUnsupported" in res.lean_code:
                    rec.update(compile="fail", why="degraded to pyUnsupported")
                else:
                    chk = leanmod.compile_check(res.lean_code)
                    if chk.ok:
                        rec.update(compile="pass")
                    else:
                        first = chk.first_error() or (chk.stderr[:80] if chk.stderr else "elaboration failed")
                        rec.update(compile="fail", why=first[:80])
            cache[mod] = rec
            _save_gate(cache)
            print(f"  [{i}/{len(todo)}] {rec.get('compile','?'):>4}  {mod}"
                  + (f"  ({rec.get('why')})" if rec.get("compile") == "fail" else ""))


def curate(dataset: Path, seed: int, provider: str, model: str | None, workers: int,
           pool_factor: float, min_ensures: int, do_compile: bool, limit: int | None) -> int:
    """Re-curate the fixed 300 by CONTRACT QUALITY, not just static heuristics. Take a headroom pool
    (`pool_factor` × the quotas), gate each on gemini stating a non-trivial theorem that compiles,
    then re-pick the final 300 from the survivors — so every benchmark problem is one a human can
    actually prove something non-trivial about. Fully resumable via `_curate/gate.json`."""
    rows = survey(dataset)
    by_problem = {r["problem"]: r for r in rows}
    candidates = _pick(rows, seed, scale=pool_factor)
    if limit:
        candidates = candidates[:limit]
    CURATE_DIR.mkdir(exist_ok=True)
    cache = _load_gate()

    _gate_contracts(candidates, dataset, provider, model, workers, min_ensures, cache, force=False)
    if do_compile:
        _gate_compile(candidates, cache, force=False)

    def survived(mod: str) -> bool:
        rec = cache.get(mod, {})
        return rec.get("contract") == "pass" and (not do_compile or rec.get("compile") == "pass")

    survivors = [by_problem[c["problem"]] for c in candidates if survived(c["module"])]
    print(f"\n[gate] {len(survivors)}/{len(candidates)} candidates passed "
          f"(contracts{' + compile' if do_compile else ''})")
    final = _pick(survivors, seed)
    # Stratified pick can fall short when a stratum (usually `class`) has < quota survivors. The bench
    # target is a full 300 that compile with a non-trivial contract, so top up from any leftover
    # survivor, deterministically (most-tested first), relaxing the quota rather than shipping < 300.
    if len(final) < 300 and len(survivors) > len(final):
        taken = {e["problem"] for e in final}
        extra = sorted((r for r in survivors if r["problem"] not in taken),
                       key=lambda r: (-r.get("n_tests", 0), r["module"]))
        for r in extra[:300 - len(final)]:
            final.append({**r, "bucket": ("term" if r["term"] else "loop"),
                          "feature": ("term" if r["term"] else (_feature_of(r) or "for"))})
    final = final[:300]
    if len(final) < 300:
        print(f"[!] only {len(final)} total survivors — RAISE --pool-factor "
              f"(currently {pool_factor}) and re-run; the pass is resumable so it re-uses cached gates.")

    manifest = {
        "source_dataset": str(dataset),
        "source_hf_repo": "newfacade/LeetCodeDataset",
        "seed": seed,
        "curated": {"provider": provider, "model": model, "min_ensures": min_ensures,
                    "pool_factor": pool_factor, "compile_gated": do_compile,
                    "candidates": len(candidates), "survivors": len(survivors)},
        "counts": _counts(final),
        "problems": final,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"[*] Curated {len(final)} problems -> {MANIFEST}")
    _print_counts(manifest["counts"])
    # Seed each chosen unit's dir + drop the gate-passing contracts in as `solution_contracts.py`,
    # so `regen` has the contracted source it should translate.
    materialize()
    for e in final:
        cf = CURATE_DIR / f"{e['module']}.contracts.py"
        dst = LEETCODE_DIR / e["module"] / CONTRACTS_FILE
        if cf.exists() and not dst.exists():
            shutil.copy2(cf, dst)
    print(f"[*] Materialized; contracts copied from {CURATE_DIR}. Next: "
          f"`pastabench.py regen` then `lake build PastaBench`.")
    return 0


# -- regeneration --------------------------------------------------------------------------

def source_of(prob_dir: Path) -> Path:
    """What gets translated. A `solution_contracts.py` — the contract-annotated twin of
    `solution.py` — takes precedence, since contracts are what make PastaLean state a theorem."""
    contracted = prob_dir / "solution_contracts.py"
    return contracted if contracted.exists() else prob_dir / "solution.py"


def targets(only: list[str] | None) -> list[dict]:
    """Every regenerable unit across both tracks. Everything translates in `both` mode so
    `Generated.lean` is the transpiler's complete output — the prove twin AND the runnable `'rn`
    twin. Dropping the twin would make the shipped file something PastaLean never emits."""
    manifest = json.loads(MANIFEST.read_text())
    out = [{"dir": LEETCODE_DIR / e["module"], "module": e["module"],
            "prefix": LEAN_NAMESPACE, "mode": "both"} for e in manifest["problems"]]
    out += [{"dir": d, "module": d.name, "prefix": STDLIB_NAMESPACE, "mode": "both"}
            for d in stdlib_modules()]
    out += [{"dir": d, "module": d.name, "prefix": HUMANEVAL_NAMESPACE, "mode": "both"}
            for d in humaneval_modules()]
    return [t for t in out if not only or t["module"] in only]


def regen(only: list[str] | None, prove: bool = True) -> int:
    """Re-translate each `solution.py` and rewrite ONLY `Generated.lean`. `Proofs.lean` is never
    read or written here — that is the whole point of the two-file split."""
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from pastalean import Session  # noqa: PLC0415  (needs the path above)

    todo = targets(only)
    if not todo:
        print("[!] nothing selected")
        return 1
    failures, done = [], 0
    for mode in sorted({t["mode"] for t in todo}):          # one warm backend per mode
        batch = [t for t in todo if t["mode"] == mode]
        with Session(target="command", mode=mode, prove_asserts=prove) as session:
            for t in batch:
                done += 1
                try:
                    result = session.translate_file(source_of(t["dir"]))
                except Exception as exc:  # noqa: BLE001  (one bad unit must not stop the sweep)
                    result, err = None, f"{type(exc).__name__}: {exc}"
                else:
                    err = result.error or "empty output"
                if result is None or not result.ok or not (result.lean_code or "").strip():
                    failures.append((t["module"], err))
                    print(f"[{done}/{len(todo)}] FAIL {t['module']}: {err.splitlines()[0][:80]}")
                    continue
                # Best-effort mode degrades an untranslatable statement to a `pyUnsupported()`
                # placeholder. That is right for a coverage sweep and WRONG here: it would
                # silently replace working generated Lean — and the proofs that cite it — with a
                # stub. In practice it means the backend was rebuilt mid-flight (never run `lake`
                # and `regen` concurrently), so refuse the write and keep what is on disk.
                if "pyUnsupported" in result.lean_code:
                    failures.append((t["module"], "degraded to pyUnsupported — kept existing file"))
                    print(f"[{done}/{len(todo)}] SKIP {t['module']}: degraded output, not written")
                    continue
                (t["dir"] / "Generated.lean").write_text(
                    namespaced(result.lean_code, t["module"], t["prefix"],
                               py_source=source_of(t["dir"]).read_text()))
                print(f"[{done}/{len(todo)}] ok   {t['module']}")
    if failures:
        print(f"\n[!] {len(failures)} failed to regenerate:")
        for module, err in failures:
            print(f"      {module}: {err.splitlines()[0][:100]}")
    return 1 if failures else 0


# -- status --------------------------------------------------------------------------------

#: A `Proofs.lean` still carrying the seeded TODO has no human proof yet.
STUB_MARKER = "-- TODO: state and prove"


def status() -> None:
    manifest = json.loads(MANIFEST.read_text())
    buckets = {e["module"]: e["bucket"] for e in manifest["problems"]}
    rows = []
    for t in targets(None):
        dst = t["dir"]
        if not dst.exists():
            continue
        proofs = (dst / "Proofs.lean").read_text() if (dst / "Proofs.lean").exists() else ""
        generated = (dst / "Generated.lean").read_text() if (dst / "Generated.lean").exists() else ""
        rows.append({
            "module": t["module"],
            "bucket": buckets.get(t["module"], "stdlib"),
            "contracts": bool(CONTRACT_RE.search(source_of(dst).read_text())),
            "spec_stated": "theorem" in generated,
            "proof_written": STUB_MARKER not in proofs and "theorem" in proofs,
            "sorry": "sorry" in proofs,
        })
    total = len(rows)
    def n(pred):
        return sum(1 for r in rows if pred(r))
    print(f"PastaBench: {total} units")
    print(f"  contracts in solution.py : {n(lambda r: r['contracts']):>4}")
    print(f"  theorem stated by Lean   : {n(lambda r: r['spec_stated']):>4}")
    print(f"  hand-written proof       : {n(lambda r: r['proof_written']):>4}")
    print(f"  proof complete (no sorry): {n(lambda r: r['proof_written'] and not r['sorry']):>4}")
    for bucket in sorted({r["bucket"] for r in rows}):
        sub = [r for r in rows if r["bucket"] == bucket]
        done = sum(1 for r in sub if r["proof_written"] and not r["sorry"])
        print(f"    {bucket:>5}: {done}/{len(sub)} proved")


# -- cli -----------------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("select", help="choose problems and write manifest.json")
    p.add_argument("--dataset", default="cp_harness/dataset_leetcode")
    p.add_argument("--seed", type=int, default=20260722)

    p = sub.add_parser("materialize", help="create per-problem dirs from manifest.json")
    p.add_argument("--force-proofs", action="store_true",
                   help="overwrite existing Proofs.lean (destroys hand-written proofs)")

    p = sub.add_parser("contracts", help="write + verify solution_contracts.py: static gates, "
                                         "behaviour identity, contract truth, mutation score, "
                                         "and a bounded LLM repair loop")
    p.add_argument("--track", choices=["leetcode", "stdlib", "humaneval"], default="humaneval")
    p.add_argument("--only", nargs="*", help="module names (default: the whole track)")
    p.add_argument("--attempts", type=int, default=2,
                   help="max LLM generations per unit that needs one; 0 = verify only, no LLM calls")
    p.add_argument("--mutants", type=int, default=30, help="mutants per unit (0 disables)")
    p.add_argument("--mutation-tests", type=int, default=12)
    p.add_argument("--min-mutation-score", type=float, default=None,
                   help="regenerate when the spec kills less than this fraction of live mutants")
    p.add_argument("--critic", action="store_true",
                   help="also ask the advisory LLM reviewer (one extra call per repair turn)")
    p.add_argument("--workers", type=int, default=6)
    p.add_argument("--provider", default="gemini")
    p.add_argument("--model", default=None, help="default: the provider's default chat model")
    p.add_argument("--report", default=None, help="write the full JSON report here")
    p.add_argument("--in-place", action="store_true",
                   help="overwrite solution_contracts.py (default: write to PastaBench/_contract_qa/)")
    p.add_argument("--verbose", "-v", action="store_true")

    p = sub.add_parser("regen", help="re-translate solution.py -> Generated.lean")
    p.add_argument("--only", nargs="*", help="module names to regenerate (default: all)")
    # Codegen-only sweep: skips the `taste?` prove-and-replace pass, which dominates regen's runtime.
    # The `def`s and spec STATEMENTS are identical; only the tactic block keeps a literal `taste?`,
    # so the output is not a shippable artifact — re-run without this before committing.
    p.add_argument("--no-prove", action="store_true",
                   help="skip the taste? proving pass (fast; leaves `taste?` in the output)")

    p = sub.add_parser("curate", help="contract-gated re-selection: pick the 300 by non-trivial "
                                      "provable property (gemini contracts + compile), resumable")
    p.add_argument("--dataset", default="cp_harness/dataset_leetcode")
    p.add_argument("--seed", type=int, default=20260722)
    p.add_argument("--provider", default="gemini")
    p.add_argument("--model", default=None, help="default: the provider's default chat model")
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--pool-factor", type=float, default=2.0,
                   help="headroom: gate this many × the quotas so 300 survive the gate")
    p.add_argument("--min-ensures", type=int, default=1,
                   help="minimum NON-TRIVIAL Ensures a problem must state to qualify")
    p.add_argument("--skip-compile", action="store_true",
                   help="gate on the Python contracts only (fast), skip the per-candidate Lean compile")
    p.add_argument("--limit", type=int, default=None, help="only gate the first N candidates (testing)")

    sub.add_parser("status", help="report contract/proof coverage")

    args = ap.parse_args()
    if args.cmd == "select":
        select((REPO_ROOT / args.dataset) if not Path(args.dataset).is_absolute()
               else Path(args.dataset), args.seed)
    elif args.cmd == "materialize":
        materialize(args.force_proofs)
    elif args.cmd == "contracts":
        return contracts(args)
    elif args.cmd == "regen":
        return regen(args.only, prove=not args.no_prove)
    elif args.cmd == "curate":
        ds = (REPO_ROOT / args.dataset) if not Path(args.dataset).is_absolute() else Path(args.dataset)
        return curate(ds, args.seed, args.provider, args.model, args.workers,
                      args.pool_factor, args.min_ensures, not args.skip_compile, args.limit)
    elif args.cmd == "status":
        status()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
